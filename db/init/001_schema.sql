-- Esquema do motor de trilhas: currículo como lista de adjacências.
-- Executado automaticamente pelo entrypoint do Postgres na primeira subida.

CREATE TABLE IF NOT EXISTS kc (
    id          text PRIMARY KEY,
    nome        text NOT NULL,
    area        text NOT NULL,
    dificuldade smallint NOT NULL CHECK (dificuldade BETWEEN 1 AND 5),
    p_init      numeric(4,3) NOT NULL DEFAULT 0.100 CHECK (p_init BETWEEN 0 AND 1),
    p_learn     numeric(4,3) NOT NULL DEFAULT 0.300 CHECK (p_learn BETWEEN 0 AND 1),
    p_slip      numeric(4,3) NOT NULL DEFAULT 0.100 CHECK (p_slip BETWEEN 0 AND 1),
    p_guess     numeric(4,3) NOT NULL DEFAULT 0.200 CHECK (p_guess BETWEEN 0 AND 1)
);

-- Aresta de pré-requisito: origem deve ser dominada antes do destino.
CREATE TABLE IF NOT EXISTS kc_prereq (
    origem_id  text NOT NULL REFERENCES kc(id) ON DELETE CASCADE,
    destino_id text NOT NULL REFERENCES kc(id) ON DELETE CASCADE,
    PRIMARY KEY (origem_id, destino_id),
    CHECK (origem_id <> destino_id)
);

CREATE INDEX IF NOT EXISTS kc_prereq_destino_idx ON kc_prereq (destino_id);

CREATE TABLE IF NOT EXISTS item (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kc_id        text NOT NULL REFERENCES kc(id) ON DELETE CASCADE,
    enunciado    text NOT NULL,
    alternativas jsonb NOT NULL CHECK (jsonb_array_length(alternativas) = 4),
    correta      text NOT NULL CHECK (correta ~ '^[a-d]$'),
    dificuldade  smallint NOT NULL DEFAULT 1 CHECK (dificuldade BETWEEN 1 AND 5)
);

CREATE INDEX IF NOT EXISTS item_kc_idx ON item (kc_id);

CREATE TABLE IF NOT EXISTS sessao (
    id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    aluno         text NOT NULL DEFAULT 'anônimo',
    target_id     text NOT NULL REFERENCES kc(id),
    criada_em     timestamptz NOT NULL DEFAULT now(),
    atualizada_em timestamptz NOT NULL DEFAULT now()
);

-- Vetor de estado do aluno: probabilidade de domínio por KC.
CREATE TABLE IF NOT EXISTS dominio (
    sessao_id     uuid NOT NULL REFERENCES sessao(id) ON DELETE CASCADE,
    kc_id         text NOT NULL REFERENCES kc(id) ON DELETE CASCADE,
    p             numeric(6,5) NOT NULL CHECK (p BETWEEN 0 AND 1),
    atualizada_em timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (sessao_id, kc_id)
);

-- Consultas analíticas por KC (taxa de domínio, evolução).
CREATE INDEX IF NOT EXISTS dominio_kc_idx ON dominio (kc_id);

CREATE TABLE IF NOT EXISTS tentativa (
    id            bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    sessao_id     uuid NOT NULL REFERENCES sessao(id) ON DELETE CASCADE,
    kc_id         text NOT NULL REFERENCES kc(id),
    item_id       bigint NOT NULL REFERENCES item(id),
    escolha       char(1) NOT NULL,
    correta       boolean NOT NULL,
    p_antes       numeric(6,5) NOT NULL,
    p_depois      numeric(6,5) NOT NULL,
    respondida_em timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS tentativa_sessao_idx ON tentativa (sessao_id, respondida_em);

-- Log de eventos do motor (replanejamentos incluídos).
CREATE TABLE IF NOT EXISTS evento (
    id        bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    sessao_id uuid NOT NULL REFERENCES sessao(id) ON DELETE CASCADE,
    tipo      text NOT NULL,
    payload   jsonb NOT NULL DEFAULT '{}'::jsonb,
    criado_em timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS evento_sessao_idx ON evento (sessao_id, criado_em);
